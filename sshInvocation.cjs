// Arguments for the system OpenSSH client (Windows or inside WSL), shared by
// streaming, directory listing and connection tests.
//
// Jump hosts: options given with -o only reach the DESTINATION, never the hosts
// in -J (see `man ssh`, -J). A jump host would otherwise run without BatchMode,
// ConnectTimeout or keepalives: it can wait forever for a prompt nobody sees, or
// drop silently. So when there is a -J, a small ssh_config is written with one
// `Host` block per jump host carrying those options, followed by an Include of
// the user's own config (aliases, users, keys keep working). OpenSSH passes -F
// on to the jump ssh processes. The file holds no secrets.

const BASE_OPTIONS = [
  ["BatchMode", "yes"],
  ["ConnectTimeout", "10"],
  ["StrictHostKeyChecking", "accept-new"],
];
const KEEPALIVE_OPTIONS = [
  ["ServerAliveInterval", "15"],
  ["ServerAliveCountMax", "3"],
];
// what every jump host gets (it carries the whole session, so always keepalive)
const HOP_OPTIONS = [...BASE_OPTIONS, ...KEEPALIVE_OPTIONS];

/* "a,b" · "user@host:2222" · "[fe80::1]:22" · "ssh://user@host:22" → host names to configure */
function parseJumpHosts(proxyJump) {
  const value = String(proxyJump || "").trim();
  if (!value) return [];
  return value.split(",").map(raw => {
    let hop = raw.trim().replace(/^ssh:\/\//i, "");
    if (!hop) throw new Error("Servidor intermedio inválido");
    const at = hop.lastIndexOf("@");
    if (at >= 0) hop = hop.slice(at + 1);
    const bracket = hop.match(/^\[([^\]]+)\](?::\d+)?$/);
    if (bracket) return bracket[1];
    const port = hop.match(/^([^:]+):(\d+)$/);
    return port ? port[1] : hop;
  });
}

function validateProxyJump(proxyJump) {
  const value = String(proxyJump || "").trim();
  if (!value) return "";
  if (value.startsWith("-") || /\s/.test(value) || /[\0"'`$;&|<>\\]/.test(value)) throw new Error("Servidor intermedio inválido");
  const hosts = parseJumpHosts(value);
  if (!hosts.length || hosts.some(host => !host || host.startsWith("-") || /[*?!]/.test(host))) {
    throw new Error("Servidor intermedio inválido");
  }
  return value;
}

const quote = value => `"${String(value).replace(/"/g, "")}"`;

/* ssh_config text: one block per jump host, then the user's/system config. */
function buildJumpConfig(hosts, { includes = [], interactive = false } = {}) {
  const unique = [...new Set(hosts)];
  const lines = ["# Generated by PulpLog for jump hosts: -o options only reach the destination host."];
  for (const host of unique) {
    lines.push(`Host ${host}`);
    // interactive: the jump host may also ask (its password, a 2FA code) through SSH_ASKPASS
    for (const [key, value] of HOP_OPTIONS) lines.push(`  ${key} ${key === "BatchMode" && interactive ? "no" : value}`);
    if (interactive) lines.push("  NumberOfPasswordPrompts 1");
  }
  if (includes.length) {
    lines.push("Match all");
    for (const file of includes) lines.push(`  Include ${quote(file)}`);
  }
  return `${lines.join("\n")}\n`;
}

/* Common arguments; the caller appends the target and the remote command.
   jumpConfigFile: path (as the ssh that runs will see it) of buildJumpConfig output. */
/* interactive: credentials will be answered through SSH_ASKPASS (askpass.cjs), so
   BatchMode must be off; one password prompt per host (a rejected secret is not retried). */
function buildSshArgs({ port = "", identityFile = "", proxyJump = "" } = {}, { keepalive = false, jumpConfigFile = null, interactive = false } = {}) {
  const args = [];
  const base = interactive
    ? [...BASE_OPTIONS.filter(([key]) => key !== "BatchMode"), ["NumberOfPasswordPrompts", "1"]]
    : BASE_OPTIONS;
  for (const [key, value] of keepalive ? [...base, ...KEEPALIVE_OPTIONS] : base) args.push("-o", `${key}=${value}`);
  if (port) args.push("-p", String(port));
  if (identityFile) args.push("-i", identityFile, "-o", "IdentitiesOnly=yes");
  const jump = validateProxyJump(proxyJump);
  if (jump) {
    if (jumpConfigFile) args.push("-F", jumpConfigFile);
    args.push("-J", jump);
  }
  return args;
}

module.exports = { parseJumpHosts, validateProxyJump, buildJumpConfig, buildSshArgs, HOP_OPTIONS };
