// Arguments for the system OpenSSH client (Windows or inside WSL), shared by
// streaming, directory listing and connection tests.
//
// Jump hosts: options given with -o only reach the DESTINATION, never the hosts
// in -J (see `man ssh`, -J). A jump host would otherwise run without BatchMode,
// ConnectTimeout or keepalives: it can wait forever for a prompt nobody sees, or
// drop silently. So when there is a -J, a small ssh_config is written with one
// `Host` block per jump host carrying those options, followed by an Include of
// the user's own config (aliases, users, keys keep working). OpenSSH passes -F
// on to the jump ssh processes. The file holds no secrets.

const BASE_OPTIONS = [
  ["BatchMode", "yes"],
  ["ConnectTimeout", "10"],
  ["StrictHostKeyChecking", "accept-new"],
];
const KEEPALIVE_OPTIONS = [
  ["ServerAliveInterval", "15"],
  ["ServerAliveCountMax", "3"],
];
// what every jump host gets (it carries the whole session, so always keepalive)
const HOP_OPTIONS = [...BASE_OPTIONS, ...KEEPALIVE_OPTIONS];

/* "a,b" · "user@host:2222" · "[fe80::1]:22" · "ssh://user@host:22" → host names to configure */
function parseJumpHosts(proxyJump) {
  const value = String(proxyJump || "").trim();
  if (!value) return [];
  return value.split(",").map(raw => {
    let hop = raw.trim().replace(/^ssh:\/\//i, "");
    if (!hop) throw new Error("Servidor intermedio inválido");
    const at = hop.lastIndexOf("@");
    if (at >= 0) hop = hop.slice(at + 1);
    const bracket = hop.match(/^\[([^\]]+)\](?::\d+)?$/);
    if (bracket) return bracket[1];
    const port = hop.match(/^([^:]+):(\d+)$/);
    return port ? port[1] : hop;
  });
}

function validateProxyJump(proxyJump) {
  const value = String(proxyJump || "").trim();
  if (!value) return "";
  if (value.startsWith("-") || /\s/.test(value) || /[\0"'`$;&|<>\\]/.test(value)) throw new Error("Servidor intermedio inválido");
  const hosts = parseJumpHosts(value);
  if (!hosts.length || hosts.some(host => !host || host.startsWith("-") || /[*?!]/.test(host))) {
    throw new Error("Servidor intermedio inválido");
  }
  return value;
}

const quote = value => `"${String(value).replace(/"/g, "")}"`;

/* ssh_config text: one block per jump host, then the user's/system config. */
function buildJumpConfig(hosts, { includes = [], interactive = false } = {}) {
  const unique = [...new Set(hosts)];
  const lines = ["# Generated by PulpLog for jump hosts: -o options only reach the destination host."];
  for (const host of unique) {
    lines.push(`Host ${host}`);
    // interactive: the jump host may also ask (its password, a 2FA code) through SSH_ASKPASS
    for (const [key, value] of HOP_OPTIONS) lines.push(`  ${key} ${key === "BatchMode" && interactive ? "no" : value}`);
    if (interactive) lines.push("  NumberOfPasswordPrompts 1");
  }
  if (includes.length) {
    lines.push("Match all");
    for (const file of includes) lines.push(`  Include ${quote(file)}`);
  }
  return `${lines.join("\n")}\n`;
}

/* Common arguments; the caller appends the target and the remote command.
   jumpConfigFile: path (as the ssh that runs will see it) of buildJumpConfig output. */
/* interactive: credentials will be answered through SSH_ASKPASS (askpass.cjs), so
   BatchMode must be off; one password prompt per host (a rejected secret is not retried). */
function buildSshArgs({ port = "", identityFile = "", proxyJump = "" } = {}, { keepalive = false, jumpConfigFile = null, interactive = false } = {}) {
  const args = [];
  const base = interactive
    ? [...BASE_OPTIONS.filter(([key]) => key !== "BatchMode"), ["NumberOfPasswordPrompts", "1"]]
    : BASE_OPTIONS;
  for (const [key, value] of keepalive ? [...base, ...KEEPALIVE_OPTIONS] : base) args.push("-o", `${key}=${value}`);
  if (port) args.push("-p", String(port));
  if (identityFile) args.push("-i", identityFile, "-o", "IdentitiesOnly=yes");
  // the chain config is needed even without -J (a single "command" hop = ProxyCommand)
  if (jumpConfigFile) args.push("-F", jumpConfigFile);
  const jump = validateProxyJump(proxyJump);
  if (jump) args.push("-J", jump);
  return args;
}

/* ─── Jump chain (structured, one entry per hop) ─────────────────────────
   hop = { type:"tunnel", host, user?, port?, identityFile?, password?, passphrase? }
       | { type:"command", command }   (ProxyCommand: AWS SSM, IAP, cloudflared, tsh…)
   A "command" hop can only be the first one: it is how your computer reaches
   the next host. Secrets stay in memory; profiles keep everything else. */
const MAX_HOPS = 6;
const HOST_RE = /^[A-Za-z0-9_.\-:%]+$|^\[[0-9A-Fa-f:.%]+\]$/;
const USER_RE = /^[A-Za-z0-9_.\-]+$/;

function normalizeHop(raw, index) {
  const type = raw?.type === "command" ? "command" : "tunnel";
  const where = `salto ${index + 1}`;
  if (type === "command") {
    if (index !== 0) throw new Error(`El ${where} es de tipo comando: solo el primer salto puede serlo`);
    const command = String(raw?.command || "").trim();
    if (!command || command.length > 1000 || /[\r\n\0]/.test(command)) throw new Error(`Comando del ${where} inválido`);
    return { type, command };
  }
  const host = String(raw?.host || "").trim();
  const user = String(raw?.user || "").trim();
  const port = String(raw?.port || "").trim();
  const identityFile = String(raw?.identityFile || "").trim();
  if (!host || host.startsWith("-") || !HOST_RE.test(host)) throw new Error(`Host del ${where} inválido`);
  if (user && (user.startsWith("-") || !USER_RE.test(user))) throw new Error(`Usuario del ${where} inválido`);
  if (port && (!/^\d+$/.test(port) || Number(port) < 1 || Number(port) > 65535)) throw new Error(`Puerto del ${where} inválido`);
  if (identityFile && /[\r\n\0"]/.test(identityFile)) throw new Error(`Llave del ${where} inválida`);
  const hop = { type, host, user, port, identityFile };
  if (raw?.password) hop.password = String(raw.password);
  if (raw?.passphrase) hop.passphrase = String(raw.passphrase);
  if (raw?.vaultCredentialId) hop.vaultCredentialId = String(raw.vaultCredentialId).slice(0, 100);
  return hop;
}

/* "user@host:port" (one hop of a ProxyJump string) → { host, user, port } */
function parseHopSpec(spec) {
  let rest = spec.trim().replace(/^ssh:\/\//i, "");
  let user = "";
  const at = rest.lastIndexOf("@");
  if (at >= 0) { user = rest.slice(0, at); rest = rest.slice(at + 1); }
  const bracket = rest.match(/^(\[[^\]]+\])(?::(\d+))?$/);
  if (bracket) return { host: bracket[1], user, port: bracket[2] || "" };
  const withPort = rest.match(/^([^:]+):(\d+)$/);
  return withPort ? { host: withPort[1], user, port: withPort[2] } : { host: rest, user, port: "" };
}

/* config.jumps (new) or config.proxyJump (text, older profiles) → validated hops */
function jumpsFromConfig(config) {
  if (Array.isArray(config?.jumps) && config.jumps.length) {
    if (config.jumps.length > MAX_HOPS) throw new Error(`Como máximo ${MAX_HOPS} saltos`);
    return config.jumps.map(normalizeHop);
  }
  const legacy = validateProxyJump(config?.proxyJump);
  return legacy ? legacy.split(",").map((spec, index) => normalizeHop({ type: "tunnel", ...parseHopSpec(spec) }, index)) : [];
}

const hopSpec = hop => `${hop.user ? `${hop.user}@` : ""}${hop.host}${hop.port ? `:${hop.port}` : ""}`;
const hostPattern = host => host.replace(/^\[|\]$/g, "");

/* -J value and per-host config for a chain. */
function chainPlan(hops, destHost) {
  const tunnels = hops.filter(hop => hop.type === "tunnel");
  const command = hops[0]?.type === "command" ? hops[0].command : null;
  return {
    jumpSpec: tunnels.map(hopSpec).join(","),
    tunnels,
    command,
    // a command hop is how we reach whatever comes right after it
    commandTarget: command ? (tunnels[0]?.host || destHost) : null,
  };
}

/* ssh_config for a chain: per-hop session options (+ key), ProxyCommand where needed,
   then the user's/system config. Needed whenever the chain is not empty. */
function buildChainConfig(plan, { includes = [], interactive = false, destHost = "" } = {}) {
  const lines = ["# Generated by PulpLog for the jump chain: -o options only reach the destination host."];
  const blocks = new Map();
  for (const hop of plan.tunnels) {
    const key = hostPattern(hop.host);
    if (blocks.has(key)) continue;
    const block = [];
    for (const [option, value] of HOP_OPTIONS) block.push(`  ${option} ${option === "BatchMode" && interactive ? "no" : value}`);
    if (interactive) block.push("  NumberOfPasswordPrompts 1");
    if (hop.identityFile) block.push(`  IdentityFile ${quote(hop.identityFile.replace(/\\/g, "/"))}`, "  IdentitiesOnly yes");
    blocks.set(key, block);
  }
  if (plan.command) {
    const key = hostPattern(plan.commandTarget || destHost);
    if (!blocks.has(key)) blocks.set(key, []);
    blocks.get(key).push(`  ProxyCommand ${plan.command}`);
  }
  for (const [host, block] of blocks) lines.push(`Host ${host}`, ...block);
  if (includes.length) {
    lines.push("Match all");
    for (const file of includes) lines.push(`  Include ${quote(file)}`);
  }
  return `${lines.join("\n")}\n`;
}

/* What may be stored (profiles, workspaces): never passwords or passphrases.
   Invalid hops are dropped instead of failing the whole profile. */
function publicJumps(jumps) {
  if (!Array.isArray(jumps)) return [];
  const out = [];
  for (const raw of jumps.slice(0, MAX_HOPS)) {
    try {
      const hop = normalizeHop(raw, out.length);
      out.push(hop.type === "command" ? { type: "command", command: hop.command }
        : { type: "tunnel", host: hop.host, user: hop.user, port: hop.port, identityFile: hop.identityFile,
            ...(hop.vaultCredentialId ? { vaultCredentialId: hop.vaultCredentialId } : {}) });
    } catch { /* skip invalid hop */ }
  }
  return out;
}

module.exports = {
  publicJumps,
  parseJumpHosts, validateProxyJump, buildJumpConfig, buildSshArgs, HOP_OPTIONS,
  normalizeHop, parseHopSpec, jumpsFromConfig, chainPlan, buildChainConfig, hopSpec, MAX_HOPS,
};
